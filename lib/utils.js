// Whitelist-based noise filter for SUCCESSFUL command output ONLY.
// A line is dropped when it is (a) clearly advisory (warning:/WARN prefix) AND
// (b) matches a known-harmless pattern. Everything else passes untouched.
// On failure paths this function must NEVER be applied: there, stderr is
// evidence, not noise.
const NOISE_PATTERNS = [
  /will be replaced by (CRLF|LF)/i, // git autocrlf line-ending notices (Windows)
  /\bdeprecat(?:ed|ion)\b/i, // deprecation advisories (git / npm)
];
function filterNoiseLines(text) {
  return String(text)
    .split(/\r?\n/)
    .filter((line) => {
      const advisory = /^\s*(warning:|\[WARN\]|npm WARN\b)/i.test(line);
      if (!advisory) return true;
      return !NOISE_PATTERNS.some((re) => re.test(line));
    })
    .join('\n');
}

function cliCommandLines(args) {
  const script = process.argv[1];
  if (!script || path.basename(script).toLowerCase() !== 'project-state.js' || !Array.isArray(args) || args.some((arg) => /[\0\r\n]/.test(String(arg)))) return [];
  const cliPath = path.resolve(script);
  if (process.platform !== 'win32') {
    const quote = (value) => `'${String(value).replace(/'/g, `'\\''`)}'`;
    return [[process.execPath, cliPath, ...args].map(quote).join(' ')];
  }
  const quotePowerShell = (value) => `'${String(value).replace(/'/g, "''")}'`;
  const powershell = `& ${[process.execPath, cliPath, ...args].map(quotePowerShell).join(' ')}`;
  const systemRoot = process.env.SystemRoot || process.env.WINDIR || 'C:\\Windows';
  const powershellPath = path.join(systemRoot, 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
  const commandPrompt = `"${powershellPath.replace(/"/g, '""')}" -NoProfile -NonInteractive -EncodedCommand ${Buffer.from(`${powershell}; exit $LASTEXITCODE`, 'utf16le').toString('base64')}`;
  return [`PowerShell: ${powershell}`, `Command Prompt: ${commandPrompt}`];
}

function cliNext(args, fallback) {
  const lines = cliCommandLines(args);
  if (!lines.length) return fallback;
  return lines.join(' OR ');
}

// SECURITY: resolve a trusted absolute path for an external command, excluding
// the project directory (and everything under it) from the search. A project
// root that is the child-process cwd must never be able to hijack our tool
// probes with a planted npm.cmd / python.exe.
const WIN_PROBE_EXTS = ['.exe', '.cmd', '.bat'];
function resolveTrustedBinary(cmd, projectRoot) {
  const rootAbs = path.resolve(projectRoot || process.cwd());
  const insideProject = (p) => {
    const rel = path.relative(rootAbs, path.resolve(p));
    return rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
  };
  const dirs = String(process.env.PATH || '')
    .split(path.delimiter)
    .map((d) => d.trim())
    .filter((d) => d.length > 0 && !insideProject(d));
  const exts = process.platform === 'win32' ? WIN_PROBE_EXTS : [''];
  for (const dir of dirs) {
    for (const ext of exts) {
      const candidate = path.join(dir, cmd + ext);
      try {
        if (fs.statSync(candidate).isFile()) {
          return { path: candidate, isScript: /\.cmd$|\.bat$/i.test(candidate) };
        }
      } catch {
        /* not here - keep searching */
      }
    }
  }
  return null;
}

// SECURITY: run an external command through a project-outside absolute binary.
// .cmd/.bat shims are executed via a TRUSTED ComSpec (absolute, outside the
// project). CMD cannot be made safe for arbitrary arguments: if any argument
// carries CMD metacharacters (% ! ^ & | < > ( )), the script invocation is
// REFUSED and surfaces as unknown/skipped - per hardening spec, refusing is
// the correct fallback when escaping cannot be guaranteed.
const CMD_UNSAFE = /[%!^&|<>()"']/;
function trustedComspec(projectRoot) {
  const rootAbs = path.resolve(projectRoot || process.cwd());
  const outside = (p) => {
    if (!path.isAbsolute(p)) return false;
    const rel = path.relative(rootAbs, path.resolve(p));
    // Outside = a different subtree ('..') or a different drive (absolute rel).
    return rel.startsWith('..') || path.isAbsolute(rel);
  };
  const candidates = [];
  if (process.env.ComSpec) candidates.push(process.env.ComSpec);
  if (process.env.SystemRoot) candidates.push(path.join(process.env.SystemRoot, 'System32', 'cmd.exe'));
  for (const c of candidates) {
    try {
      if (fs.statSync(c).isFile() && outside(c) && !CMD_UNSAFE.test(c)) return c;
    } catch {
      /* candidate missing - try next */
    }
  }
  return null;
}

function runTrusted(cmd, args, opts = {}) {
  const trusted = resolveTrustedBinary(cmd, opts.cwd || process.cwd());
  if (!trusted) {
    return Promise.resolve({
      ok: false,
      code: 'ENOENT',
      stdout: '',
      stderr: '',
      message: `trusted binary for "${cmd}" not found outside the project directory`,
    });
  }
  if (trusted.isScript) {
    const all = [trusted.path, ...args];
    const unsafe = all.find((a) => CMD_UNSAFE.test(a));
    if (unsafe !== undefined) {
      return Promise.resolve({
        ok: false,
        code: 'EREFUSED',
        stdout: '',
        stderr: '',
        message: `refused to run "${cmd}" shim: argument carries CMD metacharacters that cannot be safely escaped`,
      });
    }
    const comspec = trustedComspec(opts.cwd);
    if (!comspec) {
      return Promise.resolve({
        ok: false,
        code: 'ENOENT',
        stdout: '',
        stderr: '',
        message: `no trusted ComSpec available to run "${cmd}" shim`,
      });
    }
    const command = all.map((a) => (/\s/.test(a) ? `"${a}"` : a)).join(' ');
    // /s /c strips the first and last quote in its command string. Wrapping
    // the complete, already validated command preserves the executable's
    // inner quotes when its absolute path contains spaces. Arguments carrying
    // CMD metacharacters remain refused above.
    return run(comspec, ['/d', '/s', '/c', `"${command}"`], {
      ...opts,
      shell: false,
      // Node's normal Windows quoting escapes the embedded quotes with
      // backslashes, which cmd.exe does not treat as quote escapes. The
      // command has already been validated against CMD metacharacters above.
      windowsVerbatimArguments: true,
    });
  }
  return run(trusted.path, args, { ...opts, shell: false });
}

// SECURITY: manifest.json is UNTRUSTED input. Validate structure strictly:
// name must be a legal snapshot name and must equal the CLI-requested name
// (this also pins which secrets/ directory a snapshot may ever touch);
// layers must be a plain object with known layer ids, legal statuses, and
// the fixed per-layer JSON file name. Returns an error string or null.
const KNOWN_LAYERS = new Set(['git', 'deps', 'runtime', 'config', 'docker', 'database']);
function validateManifest(manifest, requestedName) {
  if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) {
    return 'manifest is not a JSON object';
  }
  if (typeof manifest.name !== 'string' || !NAME_RE.test(manifest.name)) {
    return `manifest.name is not a valid snapshot name`;
  }
  if (requestedName !== undefined && manifest.name !== requestedName) {
    return `manifest.name "${manifest.name}" does not match the requested snapshot "${requestedName}"`;
  }
  if (!manifest.layers || typeof manifest.layers !== 'object' || Array.isArray(manifest.layers)) {
    return 'manifest.layers is missing or not an object';
  }
  for (const [id, meta] of Object.entries(manifest.layers)) {
    if (!KNOWN_LAYERS.has(id)) return `unknown layer id "${id}"`;
    if (!meta || typeof meta !== 'object' || Array.isArray(meta)) return `layer "${id}" metadata is not an object`;
    if (meta.status !== 'collected' && meta.status !== 'skipped') return `layer "${id}" has an unknown status`;
    if (meta.status === 'collected' && meta.file !== `${id}.json`) {
      return `layer "${id}" must reference its own ${id}.json`;
    }
  }
  return null;
}

// SECURITY: restore must never write THROUGH a symlink/reparse point or
// escape the project root. Walks every path component from the project root
// down to the target (lstat - links are NOT followed) and rejects the write
// if any component, or the target itself, is a link. Throws with a reason.
async function assertNoSymlinkPath(root, target) {
  const rootAbs = path.resolve(root);
  const tgtAbs = path.resolve(target);
  const rel = path.relative(rootAbs, tgtAbs);
  if (rel === '') return; // the project root itself is fine
  if (rel.startsWith('..') || path.isAbsolute(rel)) {
    throw new Error(`restore target escapes the project root: ${tgtAbs}`);
  }
  let cur = rootAbs;
  const parts = rel.split(path.sep);
  for (const part of parts.slice(0, -1)) {
    cur = path.join(cur, part);
    let st;
    try {
      st = await fsp.lstat(cur);
    } catch {
      return; // parent does not exist yet - it will be created as a real dir
    }
    if (st.isSymbolicLink()) throw new Error(`symlink in restore path: ${cur}`);
  }
  try {
    const st = await fsp.lstat(tgtAbs);
    if (st.isSymbolicLink()) throw new Error(`refusing to write through a symlink: ${tgtAbs}`);
  } catch (e) {
    if (e.code !== 'ENOENT') throw e; // ENOENT = fresh file, fine
  }
}

// SECURITY: manifest.json and the per-layer JSON files are UNTRUSTED input.
// A layer "file" name from a hostile snapshot must never escape the snapshot
// directory. Returns the resolved safe path, or null when rejected.
function safeLayerFile(snapDir, fileName) {
  if (typeof fileName !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(fileName)) return null;
  const resolved = path.resolve(snapDir, fileName);
  const rel = path.relative(path.resolve(snapDir), resolved);
  if (rel.startsWith('..') || path.isAbsolute(rel)) return null;
  return resolved;
}

// Run an external command. Never throws on non-zero exit; returns a structured
// result so callers can degrade gracefully (partial archive beats no archive).
function run(cmd, args, opts = {}) {
  return new Promise((resolve) => {
    execFile(
      cmd,
      args,
      {
        cwd: opts.cwd || process.cwd(),
        timeout: opts.timeout || 30000,
        windowsHide: true,
        maxBuffer: opts.maxBuffer ?? 10 * 1024 * 1024,
        shell: !!opts.shell,
        windowsVerbatimArguments: !!opts.windowsVerbatimArguments,
      },
      (err, stdout, stderr) => {
        if (err) {
          // Failure path: keep stderr byte-for-byte - it is evidence.
          resolve({
            ok: false,
            code: err.code,
            stdout: stdout || '',
            stderr: stderr || '',
            message: err.message,
          });
        } else {
          // Success path: advisory noise (CRLF notices, deprecations) is
          // dropped; unknown lines always pass through.
          resolve({
            ok: true,
            code: 0,
            stdout: filterNoiseLines(stdout || ''),
            stderr: filterNoiseLines(stderr || ''),
          });
        }
      }
    );
  });
}

