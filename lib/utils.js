// Snapshot names are filesystem-safe and can never escape the snapshots directory.
const NAME_RE = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;
// Auto safety-net snapshots, as generated by restore's uniqueAutoName()
// (including the same-second collision variant auto-<stamp>-2).
const AUTO_RE = /^auto-\d{8}-\d{6}(-\d+)?$/;
// Hook-generated snapshots (v1.2: pre-commit hook). Kept as a separate prefix
// so users can tell "restore safety net" apart from "saved at commit time".
const HOOK_RE = /^hook-\d{8}-\d{6}(-\d+)?$/;
const RESERVED_NAME_RE = /^(?:auto|hook)-/i;
const SNAPSHOT_SCHEMA_VERSION = 2;
const RESTORE_POLICIES = new Set(['record-only', 'copy-file', 'restore-config', 'restore-database', 'replace-database']);
// Everything prune is allowed to manage. Named snapshots can never match.
function isAutoManaged(name) {
  return AUTO_RE.test(name) || HOOK_RE.test(name);
}

function validateSnapshotName(name, kind = 'named') {
  if (typeof name !== 'string' || !NAME_RE.test(name)) throw new Error('invalid snapshot name');
  if (!['named', 'auto', 'hook'].includes(kind)) throw new Error(`invalid snapshot kind: ${kind}`);
  if (kind === 'named' && RESERVED_NAME_RE.test(name)) throw new Error('snapshot names beginning with auto- or hook- are reserved');
  if (kind === 'auto' && !AUTO_RE.test(name)) throw new Error('auto snapshot name does not match the reserved format');
  if (kind === 'hook' && !HOOK_RE.test(name)) throw new Error('hook snapshot name does not match the reserved format');
  return true;
}

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

