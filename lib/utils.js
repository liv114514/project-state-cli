// All snapshot paths are treated as untrusted. Reject Windows ADS/drive syntax,
// traversal, device names, and control directories even when running on POSIX.
const WINDOWS_DEVICE = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\..*)?$/i;
function safeArtifactRelativePath(value) {
  if (typeof value !== 'string' || !value || value.includes('\\') || value.includes(':') || value.startsWith('/')) return false;
  const parts = value.split('/');
  if (parts.some((p) => !p || p === '.' || p === '..' || /[. ]$/.test(p) || WINDOWS_DEVICE.test(p.split('.')[0].trim()))) return false;
  if (parts.some((p) => /^\.git$/i.test(p.trim().replace(/[. ]+$/g, '')) || /^\.project-state$/i.test(p.trim().replace(/[. ]+$/g, '')))) return false;
  return true;
}

async function assertAbsolutePathChain(target) {
  let cur = path.resolve(target);
  const root = path.parse(cur).root;
  while (true) {
    const st = await fsp.lstat(cur);
    if (st.isSymbolicLink()) throw new Error(`reparse point in absolute path: ${cur}`);
    if (cur === root) break;
    cur = path.dirname(cur);
  }
}

async function assertNoReparseComponents(target, stopAt) {
  const abs = path.resolve(target);
  const stop = path.resolve(stopAt);
  const rel = path.relative(stop, abs);
  if (rel === '..' || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) throw new Error(`storage path escapes its root: ${abs}`);
  const parts = rel ? rel.split(path.sep) : [];
  await assertAbsolutePathChain(stop);
  let cur = stop;
  const stopStat = await fsp.lstat(stop);
  if (stopStat.isSymbolicLink() || !stopStat.isDirectory()) throw new Error(`unsafe storage root: ${stop}`);
  for (const part of parts) {
    cur = path.join(cur, part);
    try {
      const st = await fsp.lstat(cur);
      if (st.isSymbolicLink()) throw new Error(`reparse point in storage path: ${cur}`);
    } catch (e) { if (e.code !== 'ENOENT') throw e; }
  }
}

async function assertProjectStorageSafe(root, { create = false } = {}) {
  const rootAbs = path.resolve(root);
  await assertAbsolutePathChain(rootAbs);
  const rootStat = await fsp.lstat(rootAbs);
  if (rootStat.isSymbolicLink() || !rootStat.isDirectory()) throw new Error('project root must be a real directory');
  const state = path.join(rootAbs, STATE_DIR);
  if (create) await fsp.mkdir(state, { recursive: true });
  try { await assertNoReparseComponents(state, rootAbs); } catch (e) { if (e.code !== 'ENOENT') throw e; }
  return state;
}

async function createRealDirectories(root, target) {
  const rootAbs = path.resolve(root);
  const targetAbs = path.resolve(target);
  const rel = path.relative(rootAbs, targetAbs);
  if (rel === '..' || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) throw new Error(`directory escapes trusted root: ${targetAbs}`);
  const rootStat = await fsp.lstat(rootAbs);
  if (!rootStat.isDirectory() || rootStat.isSymbolicLink()) throw new Error(`trusted root is not a real directory: ${rootAbs}`);
  let cur = rootAbs;
  for (const part of rel ? rel.split(path.sep) : []) {
    cur = path.join(cur, part);
    try {
      const st = await fsp.lstat(cur);
      if (st.isSymbolicLink() || !st.isDirectory()) throw new Error(`unsafe directory component: ${cur}`);
    } catch (e) {
      if (e.code !== 'ENOENT') throw e;
      await fsp.mkdir(cur);
    }
  }
}

async function validateSnapshot(root, name, opts = {}) {
  if (!NAME_RE.test(String(name))) throw new Error('invalid snapshot name');
  const P = snapshotPaths(root, name);
  await assertProjectStorageSafe(root);
  await assertNoReparseComponents(P.snapDir, path.join(path.resolve(root), SNAPSHOTS_DIR));
  const stateStat = await fsp.lstat(path.join(root, STATE_DIR)).catch((e) => { throw new Error(`snapshot storage missing: ${e.message}`); });
  if (stateStat.isSymbolicLink()) throw new Error('snapshot storage is a reparse point');
  const manifestStat = await fsp.lstat(P.manifestFile);
  if (!manifestStat.isFile() || manifestStat.isSymbolicLink()) throw new Error('manifest is not a regular file');
  const manifest = await readJson(P.manifestFile);
  if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) throw new Error('manifest is not an object');
  if (manifest.schemaVersion !== SNAPSHOT_SCHEMA_VERSION) throw new Error(`unsupported snapshot schemaVersion ${manifest.schemaVersion}`);
  if (manifest.status !== 'complete') throw new Error('snapshot generation is not complete');
  if (manifest.name !== name) throw new Error('manifest name does not match requested snapshot');
  validateSnapshotName(name, manifest.kind);
  if (!Number.isFinite(Date.parse(manifest.createdAt))) throw new Error('manifest createdAt is invalid');
  if (!manifest.layers || typeof manifest.layers !== 'object' || Array.isArray(manifest.layers)) throw new Error('manifest layers are invalid');
  const artifacts = manifest.artifacts;
  if (!Array.isArray(artifacts)) throw new Error('manifest artifacts must be an array');
  if (artifacts.some((a) => a && a.storage === 'private')) await assertNoReparseComponents(P.secretsDir, path.join(path.resolve(root), SECRETS_DIR));
  const ids = new Set();
  const resolved = [];
  for (const a of artifacts) {
    if (!a || typeof a !== 'object' || Array.isArray(a)) throw new Error('artifact entry is invalid');
    if (typeof a.id !== 'string' || !a.id || ids.has(a.id)) throw new Error('artifact id is missing or duplicated');
    ids.add(a.id);
    if (!KNOWN_LAYERS.has(a.layer)) throw new Error(`artifact ${a.id} has an unknown layer`);
    if (!['public', 'private'].includes(a.storage) || a.privacy !== a.storage) throw new Error(`artifact ${a.id} has an invalid privacy/storage classification`);
    if (typeof a.required !== 'boolean' || !RESTORE_POLICIES.has(a.restore)) throw new Error(`artifact ${a.id} has invalid required/restore metadata`);
    if (!safeArtifactRelativePath(a.path)) throw new Error(`artifact ${a.id} has an unsafe path`);
    if (a.storage === 'public' && a.path.toLowerCase() === 'manifest.json') throw new Error('manifest.json cannot be declared as an artifact');
    if (resolved.some((x) => x.storage === a.storage && x.path.toLowerCase() === a.path.toLowerCase())) throw new Error(`artifact path collision at ${a.path}`);
    if (typeof a.sha256 !== 'string' || !/^[a-f0-9]{64}$/.test(a.sha256)) throw new Error(`artifact ${a.id} has an invalid sha256`);
    const base = a.storage === 'public' ? P.snapDir : P.secretsDir;
    const fullPath = path.resolve(base, ...a.path.split('/'));
    await assertNoReparseComponents(fullPath, base);
    let stat;
    try { stat = await fsp.lstat(fullPath); } catch (e) { if (a.required || opts.requireOptional) throw new Error(`artifact ${a.id} is missing: ${a.path}`); else continue; }
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`artifact ${a.id} is not a regular file`);
    const hash = sha256(await fsp.readFile(fullPath));
    if (hash !== a.sha256) throw new Error(`artifact ${a.id} integrity mismatch`);
    resolved.push({ ...a, fullPath });
  }
  for (const [layer, info] of Object.entries(manifest.layers)) {
    if (!KNOWN_LAYERS.has(layer) || !info || !['collected', 'skipped'].includes(info.status)) throw new Error(`invalid layer metadata for ${layer}`);
    if (info.status === 'collected' && !artifacts.some((a) => a.layer === layer && a.id === `layer:${layer}`)) {
      throw new Error(`collected layer ${layer} is missing its declared layer artifact`);
    }
  }
  return { manifest, artifacts: resolved, paths: P };
}

const activeLocks = new Map();
async function acquireOperationLock(root, operation) {
  const state = await assertProjectStorageSafe(root);
  try { await fsp.lstat(state); } catch (e) { if (e.code === 'ENOENT') await fsp.mkdir(state); else throw e; }
  const locks = path.join(state, 'locks');
  await createRealDirectories(state, locks);
  await assertNoReparseComponents(locks, state);
  const lockDir = path.join(locks, 'operation.lock');
  const token = crypto.randomUUID();
  try { await fsp.mkdir(lockDir); } catch (e) {
    if (e.code === 'EEXIST') throw new Error('another project-state operation is active');
    throw e;
  }
  const lock = { root: path.resolve(root), lockDir, token };
  activeLocks.set(token, lock);
  try {
    await fsp.writeFile(path.join(lockDir, 'owner.json'), JSON.stringify({ token, operation: String(operation), pid: process.pid, host: os.hostname(), startedAt: new Date().toISOString() }), { flag: 'wx' });
    await recoverStorageTransactions(root);
  } catch (e) { await fsp.rm(lockDir, { recursive: true, force: true }); activeLocks.delete(token); throw e; }
  return lock;
}
async function releaseOperationLock(lock) {
  if (!lock || !activeLocks.has(lock.token)) return false;
  const own = activeLocks.get(lock.token);
  const ownerPath = path.join(own.lockDir, 'owner.json');
  try {
    const owner = JSON.parse(await fsp.readFile(ownerPath, 'utf8'));
    if (owner.token !== own.token) throw new Error('operation lock ownership changed');
    await fsp.rm(own.lockDir, { recursive: true, force: false });
  } finally { activeLocks.delete(own.token); }
  return true;
}

async function protectSnapshot(root, name) {
  const P = snapshotPaths(root, name);
  const base = path.join(path.resolve(root), STATE_DIR, 'protected', name);
  await fsp.mkdir(base, { recursive: true });
  await assertNoReparseComponents(base, path.join(path.resolve(root), STATE_DIR));
  const token = crypto.randomUUID();
  await fsp.writeFile(path.join(base, `${token}.json`), JSON.stringify({ token, name, createdAt: new Date().toISOString() }), { flag: 'wx' });
  return token;
}
async function unprotectSnapshot(root, name, token) {
  if (!/^[a-f0-9-]{36}$/i.test(String(token))) return false;
  const file = path.join(path.resolve(root), STATE_DIR, 'protected', name, `${token}.json`);
  await fsp.rm(file, { force: true });
  try { await fsp.rmdir(path.dirname(file)); } catch { /* other references remain */ }
  return true;
}
async function isSnapshotProtected(root, name) {
  const dir = path.join(path.resolve(root), STATE_DIR, 'protected', name);
  try { await assertNoReparseComponents(dir, path.join(path.resolve(root), STATE_DIR)); return (await fsp.readdir(dir)).some((n) => n.endsWith('.json')); }
  catch (e) { if (e.code === 'ENOENT') return false; throw e; }
}

async function recoverStorageTransactions(root) {
  const rootAbs = path.resolve(root);
  const state = path.join(rootAbs, STATE_DIR);
  const txDir = path.join(state, 'transactions');
  try { await assertNoReparseComponents(txDir, state); }
  catch (e) { if (e.code === 'ENOENT') return []; throw e; }
  let names;
  try { names = await fsp.readdir(txDir); } catch (e) { if (e.code === 'ENOENT') return []; throw e; }
  const recovered = [];
  for (const file of names.filter((n) => n.endsWith('.json'))) {
    const txPath = path.join(txDir, file);
    const st = await fsp.lstat(txPath);
    if (!st.isFile() || st.isSymbolicLink()) throw new Error(`unsafe snapshot transaction journal: ${txPath}`);
    const tx = await readJson(txPath);
    if (!tx || tx.version !== 1 || !NAME_RE.test(tx.name) || !/^[a-f0-9-]{36}$/i.test(tx.token)) throw new Error(`invalid snapshot transaction journal: ${file}`);
    const P = snapshotPaths(rootAbs, tx.name);
    const oldPublic = `${P.snapDir}.old-${tx.token}`;
    const oldPrivate = `${P.secretsDir}.old-${tx.token}`;
    const stagePublic = path.join(path.dirname(P.snapDir), `.${tx.name}.stage-${tx.token}`);
    const stagePrivate = path.join(path.dirname(P.secretsDir), `.${tx.name}.stage-${tx.token}`);
    const has = async (p) => { try { await fsp.lstat(p); return true; } catch (e) { if (e.code === 'ENOENT') return false; throw e; } };
    // If the new pair is complete and hash-valid, finish committing it.
    let newValid = false;
    try { await validateSnapshot(rootAbs, tx.name); newValid = true; } catch { /* incomplete or old generation */ }
    if (newValid) {
      await fsp.rm(oldPublic, { recursive: true, force: true });
      await fsp.rm(oldPrivate, { recursive: true, force: true });
      await fsp.rm(stagePublic, { recursive: true, force: true });
      await fsp.rm(stagePrivate, { recursive: true, force: true });
      await fsp.rm(txPath, { force: true });
      recovered.push({ name: tx.name, action: 'completed' });
      continue;
    }
    const hasOldPublic = await has(oldPublic);
    const hasOldPrivate = await has(oldPrivate);
    if ((tx.hadPublic && !hasOldPublic) || (tx.hadPrivate && !hasOldPrivate)) {
      throw new Error(`snapshot transaction ${tx.name} is incomplete and a previous generation is missing; manual recovery required`);
    }
    // Roll back any partially installed new pair. Directories are moved aside
    // first, preserving evidence until the old generation is restored.
    for (const [finalPath, stagePath] of [[P.snapDir, stagePublic], [P.secretsDir, stagePrivate]]) {
      if (await has(finalPath)) {
        if (await has(stagePath)) await fsp.rm(stagePath, { recursive: true, force: true });
        await fsp.rename(finalPath, stagePath);
      }
    }
    if (tx.hadPrivate) await fsp.rename(oldPrivate, P.secretsDir);
    if (tx.hadPublic) await fsp.rename(oldPublic, P.snapDir);
    if (!tx.hadPublic) await fsp.rm(P.snapDir, { recursive: true, force: true });
    if (!tx.hadPrivate) await fsp.rm(P.secretsDir, { recursive: true, force: true });
    await fsp.rm(stagePublic, { recursive: true, force: true });
    await fsp.rm(stagePrivate, { recursive: true, force: true });
    await fsp.rm(txPath, { force: true });
    recovered.push({ name: tx.name, action: 'rolled-back' });
  }
  return recovered;
}

// Local timestamp like 20261009-003500 (used for auto-snapshot names).
function timestamp() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}`;
}

// ISO timestamp -> local-timezone "YYYY-MM-DD HH:MM" for human output.
function formatTime(iso) {
  const d = new Date(iso);
  if (isNaN(d.getTime())) return String(iso);
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

// Bytes -> compact human-readable size for prune listings.
function humanSize(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

// Storage is the single implementation of snapshot paths, validation,
// locking, pins and generation lifecycle. These forwarding helpers remain for
// old internal consumers while A/D switch to the frozen storage API; they do
// not implement a second format or acceptance rule.
const Store = require('./storage');
async function validateSnapshotCompat(root, name, opts = {}) {
  return Store.validateSnapshot(root, name, { mode: opts.mode || (opts.requirePrivate === false ? 'diagnostic' : 'restore') });
}
function validateManifestCompat(manifest, requestedName) {
  try {
    if (manifest?.schemaVersion === 1) {
      if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest) || !NAME_RE.test(manifest.name || '') || (requestedName && manifest.name !== requestedName) || !manifest.layers || typeof manifest.layers !== 'object') return 'legacy manifest is invalid';
      return null;
    }
    Store.validateManifestShape(manifest, { name: requestedName, privacy: 'public' });
    return null;
  } catch (error) { return error.message; }
}
async function assertNoSymlinkPathCompat(root, target) {
  const rel = path.relative(path.resolve(root), path.resolve(target));
  if (rel === '..' || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) throw new Error('restore target escapes project root');
  await Store.validateRestoreTarget(root, rel.split(path.sep).join('/'), 'rollback');
}
async function assertProjectStorageSafeCompat(root, { create = false } = {}) {
  return (await Store.assertRealProject(root, { createState: create })).state;
}
async function createRealDirectoriesCompat(root, target) { return Store.ensureRealDirectory(root, target); }
async function acquireOperationLockCompat(root, operation) {
  return Store.acquireOperationLock(root, { operation: String(operation || 'operation').split(':')[0] || 'operation' });
}
async function protectSnapshotCompat(root, name, generation, operationId) {
  if (typeof generation !== 'string') {
    const current = await Store.validateSnapshot(root, name, { mode: 'restore' });
    generation = current.generation;
  }
  return Store.pinSnapshot(root, { name, generation, operationId: operationId || Store.randomId(), reason: 'rollback-needed' });
}
async function unprotectSnapshotCompat(root, name, pin) {
  if (!pin || typeof pin !== 'object') throw new Error('generation-bound pin reference required');
  const lock = await Store.acquireOperationLock(root, { operation: 'unpin', operationId: pin.operationId });
  try { return await Store.unpinSnapshot(root, { name, generation: pin.generation, pinId: pin.pinId, lock, terminalOutcome: 'explicit-resolution' }); }
  finally { await lock.release(); }
}
async function isSnapshotProtectedCompat(root, name) {
  const current = await Store.validateSnapshot(root, name, { mode: 'diagnostic' });
  return current.generation ? Store.isGenerationProtected(root, name, current.generation) : false;
}
async function assertNoReparseComponentsCompat(target, stopAt) {
  const rel = path.relative(path.resolve(stopAt), path.resolve(target));
  if (rel === '..' || rel.startsWith(`..${path.sep}`) || path.isAbsolute(rel)) throw new Error('storage path escapes trusted root');
  await Store.assertNoLinks(target);
}
async function assertAbsolutePathChainCompat(target) { return Store.assertNoLinks(target, { allowMissing: false }); }
async function recoverStorageTransactionsCompat(root, lock) {
  if (!lock) throw new Error('authenticated operation lock required for storage recovery');
  return Store.recoverSnapshotTransactions(root, lock);
}

